import { Bot } from '../tests/helpers/bot';
const url = process.argv[2] ?? 'ws://localhost:7790/ws';
const b = new Bot(url, 'Testa');
const w = await b.connect();
console.log('welcome', w.server.addresses.map(a => a.url).join(' '));
await b.createAndEnter('krieger');
console.log('entered', b.zone, Math.round(b.x), Math.round(b.y), 'mobs', b.mobs.size, 'objs', b.objs.size);
b.chat('/lvl 3');
await b.sleep(300);
const m = b.nearestMob()!;
console.log('nearest mob', m.mob, Math.round(Math.hypot(m.x - b.x, m.y - b.y)));
b.chat(`/goto ${m.x + 20} ${m.y}`);
await b.sleep(300);
console.log('pos', Math.round(b.x), Math.round(b.y), 'hp', b.hp, '/', b.maxHp);
const killed = await b.fight();
await b.sleep(500);
console.log('killed', killed, 'xp', b.char.xp, 'lvl', b.char.level, 'gold', b.char.gold, 'hp', b.hp, 'drops', b.drops.size, 'dmg events', b.events.filter(e => e.k === 'dmg').length);
console.log('toasts', b.toasts.slice(-5));
b.close();
process.exit(0);
